import {createRequire} from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {pathToFileURL,fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_PATH || 'playwright');
const chrome=process.env.CHROME_BIN;
const here=path.dirname(fileURLToPath(import.meta.url));
const repo=path.resolve(here,'../../..');
const out=path.resolve(here,'generated');
fs.mkdirSync(out,{recursive:true});
const source=fs.readFileSync(path.join(repo,'experiments/tools/qa.mjs'),'utf8');
const measureSource=source.slice(source.indexOf('function measure()'),source.indexOf('\nconst browser ='));
const browser=await chromium.launch({executablePath:chrome,args:['--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:768,height:900}});
const findings={runtime:await browser.version()};
await page.setContent('<style>button{position:absolute;top:20px;width:10px;height:10px;padding:0;border:0;}#a{left:20px}#b{left:40px}</style><button id="a"></button><button id="b"></button>');
findings.touchSpacing=await page.evaluate('(() => {'+measureSource+';return measure();})()');
findings.touchSpacing.expected='Both targets fail circle-circle spacing: centers 20px apart, required 24px. Current smallTargets is empty.';
await page.setContent('<h1 style="font-size:40px;line-height:60px;white-space:nowrap">신규 <span style="font-size:12px">가입</span> 혜택</h1>');
const mixed=path.join(out,'mixed-font.html');
fs.writeFileSync(mixed,await page.content());
await page.screenshot({path:path.join(out,'mixed-font-one-line.png')});
const script=path.join(repo,'skills/ko-heading-wrap/scripts/heading-lines.mjs');
const env={...process.env};
function runHeading(file,extra){const r=spawnSync(process.execPath,[script,file,'--widths','768','--json',...extra],{encoding:'utf8',env});let validJson=true;try{JSON.parse(r.stdout)}catch{validJson=false}return {status:r.status,stdout:r.stdout,stderr:r.stderr,validJson};}
findings.mixedFont=runHeading(mixed,['--keep','신규 가입 혜택']);
const absent=path.join(out,'absent-phrase.html');
fs.writeFileSync(absent,'<!doctype html><h1>다른 제목</h1>');
findings.absentPhrase=runHeading(absent,['--keep','신규 가입 혜택']);
const key=JSON.parse(fs.readFileSync(path.join(repo,'experiments/eval/human-blind-headings-key.json'),'utf8')).key;
const pre=JSON.parse(fs.readFileSync(path.join(here,'blind-headings-pre-key.json'),'utf8'));
findings.blindDecoded=Object.entries(pre.ratings).map(([id,r])=>({id,...r,...key[id],preferred:r.read===null?null:r.read==='T'?'tie':key[id][r.read==='L'?'left':'right']}));
findings.reportAudit=[];
for(const dir of fs.readdirSync(path.join(repo,'experiments/runs'))){const p=path.join(repo,'experiments/runs',dir,'qa/report.json');if(!fs.existsSync(p))continue;const r=JSON.parse(fs.readFileSync(p,'utf8'));findings.reportAudit.push({run:dir,widths:r.sweep.widths.length,raw:r.sweepRaw.length,defects:r.defects.reduce((acc,x)=>(acc[x.type]=(acc[x.type]||0)+1,acc),{}),headings:r.sweepRaw.find(x=>x.vw===375)?.korean.filter(x=>/^h1/.test(x.el))});}
await page.goto(pathToFileURL(path.join(repo,'experiments/eval/human-blind-headings/index.html')).href);
await page.evaluate(()=>localStorage.setItem('human-blind-v1',JSON.stringify({P01:{read:'L',awk:'R',why:'headings sentinel'}})));
await page.goto(pathToFileURL(path.join(repo,'experiments/eval/human-blind/index.html')).href);
findings.localStorage={pageOrigin:await page.evaluate(()=>location.origin),storage:await page.evaluate(()=>localStorage.getItem('human-blind-v1')),whyInOtherPack:await page.locator('#why').inputValue()};
await page.goto(pathToFileURL(path.join(out,'rerender/T3b-C-1.html')).href);
await page.evaluate(()=>document.fonts.ready);
findings.restoredFont=await page.evaluate(()=>({fonts:[...document.fonts].map(x=>({family:x.family,weight:x.weight,status:x.status})),h1Size:getComputedStyle(document.querySelector('h1')).fontSize,activeFont:getComputedStyle(document.querySelector('h1')).fontFamily}));
await browser.close();
fs.writeFileSync(path.join(out,'reproduction-results.json'),JSON.stringify(findings,null,2));
console.log(JSON.stringify({runtime:findings.runtime,touchSpacing:findings.touchSpacing.smallTargets,mixedFont:findings.mixedFont,absentPhrase:findings.absentPhrase,localStorage:findings.localStorage,reports:findings.reportAudit.length},null,2));
